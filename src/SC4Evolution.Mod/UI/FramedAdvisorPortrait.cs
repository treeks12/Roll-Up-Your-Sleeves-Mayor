using System;
using ColossalFramework.UI;
using SC4Evolution.Core;
using UnityEngine;

namespace SC4Evolution.Mod.UI
{
    /// <summary>Frames the local square portrait without changing its texture or native material lifetime.</summary>
    public sealed class FramedAdvisorPortrait : UITextureSprite
    {
        private static readonly int[] QuadTriangles = new int[] { 0, 1, 3, 3, 1, 2 };
        private static readonly PortraitFrame FullFrame = new PortraitFrame(0, 0, 384);

        // Presentation choices after inspecting each local 384px source, not original SC4 viewports.
        // Columns follow AdvisorMood: Calm, Concerned, Angry, Pleased. Pixel bounds use a top-left origin.
        private static readonly PortraitFrame[,] Frames = new PortraitFrame[,]
        {
            { F(128, 92, 144), F(128, 92, 144), F(222, 112, 128), F(128, 92, 144) }, // Finance
            { F(72, 78, 224), F(72, 82, 224), F(194, 48, 168), F(108, 50, 160) }, // Urban planning
            { F(110, 58, 160), F(118, 94, 160), F(194, 56, 168), F(110, 58, 160) }, // Education/health
            { F(120, 82, 160), F(116, 44, 176), F(194, 84, 176), F(128, 88, 160) }, // Utilities
            { F(108, 48, 168), F(110, 44, 160), F(194, 48, 168), F(108, 46, 168) }, // Public safety
            { F(108, 32, 168), F(122, 44, 176), F(198, 34, 176), F(110, 40, 168) }, // Environment
            { F(104, 50, 168), F(114, 54, 176), F(194, 52, 168), F(104, 50, 168) }  // Transport
        };

        private PortraitFrame _frame = FullFrame;
        internal Rect FramingBounds { get { return _frame.Bounds; } }

        internal void SetFraming(AdvisorId advisor, AdvisorMood mood)
        {
            int row = (int)advisor;
            int column = (int)mood;
            PortraitFrame frame = row >= 0 && row < Frames.GetLength(0) && column >= 0 && column < Frames.GetLength(1)
                ? Frames[row, column] : FullFrame;
            if (ReferenceEquals(_frame, frame)) return;
            _frame = frame;
            Invalidate();
        }

        protected override void OnRebuildRenderData()
        {
            base.OnRebuildRenderData();
            UIRenderData data = renderData;
            if (!IsNativeQuad(data)) return;
            Rect bounds = _frame.Bounds;
            // Use the UVs already generated by the native renderer, including its flip/fill.
            // Validation above is complete before any write; unexpected geometry keeps native UVs.
            for (int i = 0; i < 4; i++)
            {
                Vector2 uv = data.uvs[i];
                data.uvs[i] = new Vector2(bounds.x + uv.x * bounds.width, bounds.y + uv.y * bounds.height);
            }
        }

        private static bool IsNativeQuad(UIRenderData data)
        {
            if (data == null || data.vertices == null || data.uvs == null || data.triangles == null
                || data.vertices.Count != 4 || data.uvs.Count != 4 || data.triangles.Count != QuadTriangles.Length)
                return false;
            for (int i = 0; i < QuadTriangles.Length; i++)
                if (data.triangles[i] != QuadTriangles[i]) return false;
            for (int i = 0; i < 4; i++)
            {
                Vector2 uv = data.uvs[i];
                Vector3 vertex = data.vertices[i];
                if (!Finite(uv.x) || !Finite(uv.y) || uv.x < 0f || uv.x > 1f || uv.y < 0f || uv.y > 1f
                    || !Finite(vertex.x) || !Finite(vertex.y) || !Finite(vertex.z)) return false;
            }
            Vector3 a = data.vertices[0], b = data.vertices[1], c = data.vertices[2], d = data.vertices[3];
            return Mathf.Approximately(a.y, b.y) && Mathf.Approximately(c.y, d.y)
                && Mathf.Approximately(a.x, d.x) && Mathf.Approximately(b.x, c.x)
                && Mathf.Approximately(a.z, b.z) && Mathf.Approximately(a.z, c.z) && Mathf.Approximately(a.z, d.z)
                && a.x <= b.x && d.y <= a.y;
        }

        private static bool Finite(float value) { return !float.IsNaN(value) && !float.IsInfinity(value); }
        private static PortraitFrame F(int left, int top, int size) { return new PortraitFrame(left, top, size); }

        /// <summary>Immutable square frame; only validated normalized values reach the render path.</summary>
        private sealed class PortraitFrame
        {
            private readonly float _left, _bottom, _size;
            internal Rect Bounds { get { return new Rect(_left, _bottom, _size, _size); } }

            internal PortraitFrame(int left, int top, int size)
            {
                if (left < 0 || top < 0 || size <= 0 || size > 384 || left > 384 - size || top > 384 - size)
                    throw new ArgumentOutOfRangeException("size", "Portrait framing must stay within the square source.");
                _left = left / 384f;
                _bottom = (384 - top - size) / 384f;
                _size = size / 384f;
                if (!Finite(_left) || !Finite(_bottom) || !Finite(_size) || _left < 0f || _bottom < 0f
                    || _left + _size > 1f || _bottom + _size > 1f)
                    throw new ArgumentOutOfRangeException("size", "Portrait UVs must remain within zero and one.");
            }
        }
    }
}
